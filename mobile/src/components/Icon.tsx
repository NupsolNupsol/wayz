export type IconName = keyof typeof REGISTRY

export function Icon({
  name,
  size = 20,
  color = COLORS.navy,
  strokeWidth = 2,
}: {
  name: IconName | string
  size?: number
  color?: string
  strokeWidth?: number
}) {
  const Glyph = REGISTRY[name as IconName] ?? Package
  return <Glyph size={size} color={color} strokeWidth={strokeWidth} />
}
