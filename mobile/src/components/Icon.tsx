/**
 * Every glyph the apps may name, in one registry.
 *
 * Screens pass a name rather than importing lucide directly: it keeps icon choices reviewable in
 * one place, lets the API hand back an icon name as data, and means an unknown name degrades to a
 * parcel instead of crashing the render.
 */
